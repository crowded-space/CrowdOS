#!/usr/bin/env node
/**
 * CFG-1 · generate-env-doc
 * Imports the zod envSchema and emits docs/environment.md as a table generated from schema.
 * Usage: npm run gen:env-doc  (via tsx)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// When run via `tsx scripts/generate-env-doc.mjs`, tsx resolves .ts imports.
// We import with explicit .ts extension relative to this file.
import { envSchema } from '../src/Shared/config/env.ts';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..', '..', '..');
const outPath = path.join(repoRoot, 'docs', 'environment.md');

// Helpers to introspect zod field for docs
function findEnumValues(node, visited = new Set()) {
  if (!node || visited.has(node)) return null;
  visited.add(node);
  const def = node._def ?? node.def ?? node._zod?.def;
  if (!def) {
    // also try node itself as bag
    if (node.values && Array.isArray(node.values)) return node.values;
    return null;
  }
  if (def.values && Array.isArray(def.values)) return def.values;
  if (def.entries && typeof def.entries === 'object' && !Array.isArray(def.entries)) {
    // ZodEnum in v4 stores entries
    const keys = Object.keys(def.entries);
    if (keys.length && keys.every(k => typeof k === 'string')) return keys;
  }
  // Check common inner wrappers
  const candidates = [];
  if (def.innerType) candidates.push(def.innerType);
  if (def.in) candidates.push(def.in);
  if (def.out) candidates.push(def.out);
  if (def.schema) candidates.push(def.schema);
  // ZodDefault wraps innerType, ZodOptional, ZodPipe, ZodTransform, etc.
  for (const c of candidates) {
    const r = findEnumValues(c, visited);
    if (r) return r;
  }
  // Try _zod bag
  if (node._zod && node._zod !== node) {
    const r = findEnumValues(node._zod, visited);
    if (r) return r;
  }
  // Try def's inner bag
  if (def.innerType?._zod) {
    const r = findEnumValues(def.innerType._zod, visited);
    if (r) return r;
  }
  return null;
}

function formatDefault(v) {
  if (v === undefined) return '—';
  if (v === null) return '`null`';
  if (typeof v === 'string') {
    if (v === '') return '""';
    // truncate long urls? show full
    return '`' + v.replace(/`/g, '\\`') + '`';
  }
  if (typeof v === 'boolean') return '`' + String(v) + '`';
  if (typeof v === 'number') return '`' + String(v) + '`';
  return '`' + String(v).replace(/`/g, '\\`') + '`';
}

function escapeMd(s) {
  return String(s).replace(/\|/g, '\\|').replace(/\n/g, '<br>');
}

const shape = envSchema.shape;
const keys = Object.keys(shape).sort();

let rows = [];
for (const key of keys) {
  const field = shape[key];
  const desc = (field.description ?? '').trim().replace(/\s+/g, ' ');
  // default via safeParse(undefined)
  let defVal;
  try {
    const parsed = field.safeParse(undefined);
    defVal = parsed.success ? parsed.data : undefined;
  } catch {
    defVal = undefined;
  }
  // infer type
  let typeStr = '';
  const enumVals = findEnumValues(field);
  if (enumVals && enumVals.length) {
    typeStr = enumVals.map(v => '`' + v + '`').join(' \\| ');
  } else if (typeof defVal === 'boolean') {
    typeStr = 'boolean';
  } else if (typeof defVal === 'number') {
    // check if integer
    typeStr = Number.isInteger(defVal) ? 'integer' : 'number';
    // try to enrich with bounds from description
  } else if (typeof defVal === 'string') {
    // if key ends with _URL, it's url
    if (key.endsWith('_URL')) typeStr = 'string (url)';
    else typeStr = 'string';
  } else {
    // optional without default -> infer from description or fallback
    if (key.endsWith('_URL')) typeStr = 'string (url, optional)';
    else if (key === 'HOST' || key === 'CORS_ORIGIN' || key.startsWith('AUTH_') || key.startsWith('CREDENTIALS_')) typeStr = 'string (optional)';
    else typeStr = 'string (optional)';
    // refine for bools that are optional? but all bools have defaults
  }

  // For optional fields with no default, show — and type as optional
  const defDisplay = formatDefault(defVal);
  rows.push({ key, typeStr, defDisplay, desc });
}

const header = `# Environment Configuration

> **Generated from \`packages/server/src/Shared/config/env.ts\` via \`npm run gen:env-doc\`. Do not edit this file by hand — run the generator to refresh.**
> Last generated: ${new Date().toISOString()}

CrowdOS fails fast on boot if any known variable is malformed or any project-prefixed unknown variable is present while \`CONFIG_STRICT=true\` (default). See [Strictness](#strictness) below.

## Variables

| Variable | Type | Default | Description |
|---|---|---|---|
`;

let body = rows.map(r => `| \`${r.key}\` | ${r.typeStr} | ${r.defDisplay} | ${escapeMd(r.desc)} |`).join('\n');

const strictness = `
## Strictness

### Unknown variable handling

Project-prefixed variables are those matching any of:

\`AUTH_\`, \`QUEUE_\`, \`REDIS_\`, \`SOCKET_\`, \`PROVIDER_\`, \`MEM_\`, \`RETENTION_\`, \`BUDGET_\`, \`RATE_LIMIT_\`, \`METRICS_\`, \`MAX_PARALLEL\`, \`STREAM_BATCH\`, \`TOOL_RWP\`, \`MODEL_ROUTE\`, \`DELTA_INDEX\`, \`PER_ITERATION\`, \`RUNS_ENABLED\`, \`DURABLE_EVENTS\`, \`DEMO_FALLBACK\`, \`SWARM_\`, \`APPROVALS_\`, \`LEGACY_\`, \`CREDENTIALS_\`, \`PIPELINE_\`, \`ORPHAN_\`

or exactly: \`DATABASE_URL\`, \`WORKSPACE_ADMIN_TOKEN\`, \`PORT\`, \`HOST\`, \`CORS_ORIGIN\`.

Any env var matching that namespace but not present in the schema is **unknown**.

- \`CONFIG_STRICT=true\` (default): boot **blocks** with \`ConfigError\` listing every unknown var plus a fix hint: correct the spelling, remove the var, extend \`Shared/config/env.ts\`, or set \`CONFIG_STRICT=false\` to downgrade to warning.
- \`CONFIG_STRICT=false\`: boot proceeds, unknown vars are reported in the redacted boot report as warnings (rollback / lenient parser flag).

OS junk (e.g. \`PATH\`, \`HOME\`, \`HOSTNAME\`, \`CI\`, \`npm_*\`, provider API keys like \`OPENAI_API_KEY\` — anything not matching the project namespace) is **never flagged**.

### Malformed known variable handling

Any known variable whose value fails its zod check (wrong type, out-of-bounds int, invalid enum, malformed url, non-boolean string where boolean expected) **always blocks boot** regardless of \`CONFIG_STRICT\`, with a message of the form:

\`\`\`
[config] Invalid environment configuration — fix these before boot:
- VAR: <zod message> (received "<raw>")
\`\`\`

The fix is to set the var to a value matching its expected shape (see Type/Default column) or unset it to accept the default.

### Boot report

On successful boot, \`initConfig({ log })\` prints the effective config with secrets redacted:

- Keys matching \`/KEY|TOKEN|PASSWORD|SECRET/i\` → \`[redacted]\`
- Keys ending \`_URL\` → origin only (e.g. \`https://db.example.com\`)
- All other vars → their parsed value

Coerced vars (where normalized value differs from raw string, e.g. \`"  true "\` → \`true\`, \`"42 "\` → \`42\`) are reported as warnings.

## Usage

\`\`\`ts
import { initConfig } from './Shared/config/env.js';

// At top of src/index.ts (or worker.ts) before any other imports that read config:
const { config, issues } = initConfig({ log: true });
// config is the typed EffectiveConfig
// issues.unknownProjectVars / issues.coerced are available for telemetry
\`\`\`

Typed access after boot:

\`\`\`ts
import { appConfig } from './Shared/config/env.js';
console.log(appConfig.PORT); // throws if read before initConfig()
\`\`\`

Legacy import still works (but now validates via schema internally):

\`\`\`ts
import { env } from './Shared/config/env.js';
\`\`\`

## Generation

\`\`\`sh
npm run gen:env-doc --workspace @community-agent/server
# or from repo root:
npm run gen:env-doc  # if wired there
\`\`\`

Source of truth: \`envSchema\` in \`packages/server/src/Shared/config/env.ts\` — every field has a \`.describe()\` used to populate the Description column above.

## .env.example

\`.env.example\` is kept aligned with this table. When adding a new variable:

1. Add it to \`envSchema\` with correct coercion and \`.describe()\`
2. Run \`npm run gen:env-doc\` to refresh this file
3. Update \`.env.example\` with the same default and a comment copied from the Description column
`;

const out = header + body + strictness + '\n';

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out, 'utf8');
console.log(`[gen:env-doc] wrote ${outPath} (${keys.length} vars)`);

